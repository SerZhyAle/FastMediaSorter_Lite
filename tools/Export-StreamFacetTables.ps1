<#
.SYNOPSIS
  Generates src/Streams/StreamFacetTables.vb from the vendored STREAM-BANK facet tables.

.DESCRIPTION
  STREAM-BANK rule 14 (item O) closes the `language` and `country` columns of the stream catalog to a vocabulary and an
  assigned-code list; item P says a second producer PORTS the catalog's published tables and replays the golden vectors.
  The five table files live, byte for byte, in tests/Lite.Tests/TestData/stream-facets/ beside a PROVENANCE.txt (taken
  from the catalog folder, never edited here). This script turns them into one VB source file of string arrays, so the
  data travels inside the exe with no resource plumbing. The whole file is `#If Not NETFRAMEWORK`, like the rest of
  src/Streams/: the catalogue producer is mainline only, and the net48 fallback keeps the file in its list (CLAUDE.md,
  "a new file has to be added to the net48 list BY HAND") without carrying 33 KB of tables it never reads.

  The output is never edited by hand: re-run this script after re-taking the six files, then update the digests in
  PROVENANCE.txt. StreamFacetFoldTests holds the generated file to its source (every row, in order) and the source files
  to the digests in PROVENANCE.txt.

  Default is to write the file. With -Check the file is not written: the script exits 0 when the committed file equals
  what would be generated, 1 when it differs (a stale generated file), and 2 when an input is missing.

.PARAMETER Check
  Compare instead of write.
#>
[CmdletBinding()]
param([switch]$Check)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$dataDir = Join-Path $root 'tests\Lite.Tests\TestData\stream-facets'
$target = Join-Path $root 'src\Streams\StreamFacetTables.vb'

$sources = [ordered]@{
    LanguageVocabulary = @{ File = 'facet-language-vocabulary.tsv'; Columns = 4; Header = 'name' }
    LanguageAliases    = @{ File = 'facet-language-aliases.tsv';    Columns = 2; Header = 'alias' }
    CountryAssigned    = @{ File = 'facet-country-assigned.tsv';    Columns = 1; Header = 'code' }
    CountryAliases     = @{ File = 'facet-country-aliases.tsv';     Columns = 2; Header = 'alias' }
    CountryNames       = @{ File = 'facet-country-names.tsv';       Columns = 2; Header = 'name' }
}

foreach ($name in $sources.Keys) {
    $path = Join-Path $dataDir $sources[$name].File
    if (-not (Test-Path -LiteralPath $path)) {
        Write-Host ("Export-StreamFacetTables: COULD NOT VERIFY - missing input {0}" -f $path)
        exit 2
    }
}

function Get-Rows([string]$path, [int]$columns, [string]$header) {
    $rows = New-Object System.Collections.Generic.List[string]
    $sawHeader = $false
    foreach ($line in [System.IO.File]::ReadAllLines($path, [System.Text.Encoding]::UTF8)) {
        if ($line.Length -eq 0 -or $line.StartsWith('#')) { continue }
        $fields = $line.Split("`t")
        if (-not $sawHeader) {
            if ($fields[0] -ne $header) { throw "$path : the first data line is '$($fields[0])', expected the header '$header'." }
            $sawHeader = $true
            continue
        }
        $padded = New-Object 'string[]' $columns
        for ($i = 0; $i -lt $columns; $i++) { $padded[$i] = if ($i -lt $fields.Length) { $fields[$i] } else { '' } }
        if ($fields.Length -gt $columns) { throw "$path : more than $columns columns in '$line'." }
        $rows.Add(($padded -join '|'))
    }
    if (-not $sawHeader) { throw "$path : no header row." }
    return , $rows
}

$sb = New-Object System.Text.StringBuilder
$eol = "`r`n"
[void]$sb.Append('#If Not NETFRAMEWORK Then' + $eol)
[void]$sb.Append('Option Strict On' + $eol + $eol)
[void]$sb.Append("' GENERATED by tools/Export-StreamFacetTables.ps1 from tests/Lite.Tests/TestData/stream-facets/*.tsv - NEVER EDIT BY HAND." + $eol)
[void]$sb.Append("' STREAM-BANK rule 14 (item O) closes the `language` and `country` columns; item P publishes the tables a second producer ports." + $eol)
[void]$sb.Append("' The five source files are the catalog's own (see PROVENANCE.txt there for the digests, the date and the open question whether" + $eol)
[void]$sb.Append("' they are the published artifact). A row is one string, its fields joined by '|' (no field holds one):" + $eol)
[void]$sb.Append("'   LanguageVocabulary  name|iso639_1|iso639_2 (comma list)|iso639_3_extension" + $eol)
[void]$sb.Append("'   LanguageAliases     spelling|canonical (a comma in the target means several languages)" + $eol)
[void]$sb.Append("'   CountryAssigned     code" + $eol)
[void]$sb.Append("'   CountryAliases      spelling|code" + $eol)
[void]$sb.Append("'   CountryNames        folded platform region name|code" + $eol)
[void]$sb.Append("' Source digests:" + $eol)
foreach ($name in $sources.Keys) {
    $path = Join-Path $dataDir $sources[$name].File
    $hash = (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash.ToLowerInvariant()
    [void]$sb.Append(("'   {0}  {1}" -f $hash, $sources[$name].File) + $eol)
}
[void]$sb.Append($eol)
[void]$sb.Append('Namespace Streams' + $eol + $eol)
[void]$sb.Append('    Friend NotInheritable Class StreamFacetTables' + $eol + $eol)
[void]$sb.Append('        Private Sub New()' + $eol + '        End Sub' + $eol)

foreach ($name in $sources.Keys) {
    $spec = $sources[$name]
    $rows = Get-Rows (Join-Path $dataDir $spec.File) $spec.Columns $spec.Header
    [void]$sb.Append($eol)
    [void]$sb.Append(("        ' {0}: {1} rows" -f $spec.File, $rows.Count) + $eol)
    [void]$sb.Append(("        Friend Shared ReadOnly {0} As String() = {{" -f $name) + $eol)
    for ($i = 0; $i -lt $rows.Count; $i++) {
        $literal = '"' + $rows[$i].Replace('"', '""') + '"'
        $comma = if ($i -lt $rows.Count - 1) { ',' } else { '' }
        [void]$sb.Append(('            ' + $literal + $comma) + $eol)
    }
    [void]$sb.Append('        }' + $eol)
}

[void]$sb.Append($eol + '    End Class' + $eol + $eol + 'End Namespace' + $eol + '#End If' + $eol)
$text = $sb.ToString()

if ($Check) {
    if (-not (Test-Path -LiteralPath $target)) {
        Write-Host 'Export-StreamFacetTables: FAIL - src/Streams/StreamFacetTables.vb does not exist; run the script without -Check.'
        exit 1
    }
    # Line endings are not part of the comparison: git may hand a clone the file with LF or CRLF.
    $existing = [System.IO.File]::ReadAllText($target, [System.Text.Encoding]::UTF8).Replace("`r`n", "`n")
    if ($existing -ceq $text.Replace("`r`n", "`n")) {
        Write-Host 'Export-StreamFacetTables: PASS - the generated file is up to date.'
        exit 0
    }
    Write-Host 'Export-StreamFacetTables: FAIL - src/Streams/StreamFacetTables.vb differs from what the vendored tables generate; run the script without -Check.'
    exit 1
}

# UTF-8 WITH a byte-order mark: the net48 project is compiled by the old vbc, which reads a BOM-less file in the
# system code page and would turn every native-script spelling into mojibake.
[System.IO.File]::WriteAllText($target, $text, (New-Object System.Text.UTF8Encoding($true)))
Write-Host ("Export-StreamFacetTables: wrote {0} ({1} bytes of text)" -f $target, $text.Length)
exit 0
