<#
.SYNOPSIS
    Fixture-driven self-test of the audit-campaign tools of ticket 057: tools/Audit-Partition.ps1,
    tools/Audit-FanOut.ps1 and tools/Audit-Status.ps1 (spec 057 section 9).

.DESCRIPTION
    Builds a small fixture tree in %TEMP% - its own concern map, class A files, a Designer file, a
    string table, an unmapped file and a class B test - and holds the three tools to their promises:
      partition - each class A file in exactly one slice; limits held; a repeated run gives the same
                  manifest byte for byte; an oversized concern split, a small one merged; a partial
                  kept with its helper; an unmapped file reported; a Designer file excluded with its
                  reason; -IncludeClassB changes membership only by adding class B files;
      fan-out   - one file per slice; queue lines in risk order under the umbrella; a second run
                  creates nothing and changes no byte of the queue; existing lines untouched;
      status    - exit 2 without a manifest; exit 1 with open slices, naming them and the unmapped
                  file; exit 1 naming a doubled file and an unaccounted P1; exit 0 when all is done.
    Nothing outside the fixture folder is written.

    Exit codes (CHECK-VERDICT): 0 - every assertion held; 1 - an assertion failed; 2 - could not
    verify (the fixture could not be built or a tool is missing). The last line is the verdict,
    `AuditCampaign: <WORD> (..)`.
#>
[CmdletBinding()]
param([switch]$Keep)

$ErrorActionPreference = 'Stop'
$repo = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
. (Join-Path $repo 'tools\lib\Verdict.ps1')

trap {
    Write-Host "  $($_.Exception.Message)"
    Exit-Verdict 'AuditCampaign' 2 'the check itself failed'
}

$tools = Join-Path $repo 'tools'
foreach ($t in 'Audit-Partition.ps1', 'Audit-FanOut.ps1', 'Audit-Status.ps1', 'audit-slice-template.md') {
    if (-not (Test-Path -LiteralPath (Join-Path $tools $t))) { Exit-Verdict 'AuditCampaign' 2 "tools/$t not found" }
}
Write-Subject 'AuditCampaign' "the audit-campaign tools in $(Get-TreeLabel $repo), against a fixture tree"

$fx = Join-Path ([System.IO.Path]::GetTempPath()) ("fms-audit-fixture-" + [guid]::NewGuid().ToString('N').Substring(0, 8))
$failures = [System.Collections.Generic.List[string]]::new()
$passed = 0
function Assert([bool]$Cond, [string]$What) {
    if ($Cond) { $script:passed++; Write-Host "  ok   $What" } else { $script:failures.Add($What); Write-Host "  FAIL $What" -ForegroundColor Red }
}
function Put([string]$Rel, [string[]]$Lines) {
    $p = Join-Path $fx $Rel
    $d = Split-Path -Parent $p
    if (-not (Test-Path -LiteralPath $d)) { [void](New-Item -ItemType Directory -Path $d -Force) }
    [System.IO.File]::WriteAllText($p, (($Lines -join "`n") + "`n"), [System.Text.UTF8Encoding]::new($false))
}
function Filler([int]$N) { @(1..$N | ForEach-Object { "' line $_" }) }
$pwsh = (Get-Process -Id $PID).Path
function Run([string]$Tool, [string[]]$ToolArgs) {
    $prev = $ErrorActionPreference; $ErrorActionPreference = 'Continue'
    try { $out = @(& $pwsh -NoProfile -File (Join-Path $tools $Tool) @ToolArgs 2>&1 | ForEach-Object { "$_" }) }
    finally { $ErrorActionPreference = $prev }
    [pscustomobject]@{ Code = $LASTEXITCODE; Out = ($out -join "`n") }
}

try {
    # --- the fixture -----------------------------------------------------------
    Put 'tools/audit-concerns.json' @(
        '{',
        '  "roots": [ "src/**/*.vb" ],',
        '  "classBRoots": [ "tests/**/*.vb" ],',
        '  "skipDirs": [ "bin", "obj" ],',
        '  "excluded": [ { "pattern": "**/*.Designer.vb", "reason": "generated by the designer" } ],',
        '  "data": [ { "pattern": "src/Loc/Loc.*.vb", "coveredBy": "ParityTests", "sampledBy": "L-loc" } ],',
        '  "groupAliases": {},',
        '  "concerns": [',
        '    { "id": "X-big", "title": "big", "area045": "", "patterns": [ "src/Big/*.vb", "src/*Foo.vb" ] },',
        '    { "id": "Y-small", "title": "small", "area045": "", "patterns": [ "src/Small.vb" ] },',
        '    { "id": "Z-mid", "title": "mid", "area045": "", "patterns": [ "src/Mid*.vb" ] },',
        '    { "id": "L-loc", "title": "loc", "area045": "", "patterns": [ "src/Loc/Loc.vb" ] },',
        '    { "id": "T-tests", "title": "tests", "area045": "", "classB": true, "patterns": [ "tests/**" ] }',
        '  ]',
        '}')
    foreach ($n in 'A', 'B', 'C', 'D', 'E') { Put "src/Big/$n.vb" (Filler 40) }
    Put 'src/Main_Form.Foo.vb' (@('Public Class F', '  Sub New()', '    AddHandler btn.Click, AddressOf OnClick', '    Try', '      Work()', '    Catch ex As Exception', '      Debug.WriteLine("x")', '    End Try', '  End Sub') + (Filler 21))
    Put 'src/Foo.vb' (Filler 20)
    Put 'src/Small.vb' (Filler 5)
    Put 'src/Mid1.vb' (Filler 30)
    Put 'src/Mid2.vb' (Filler 30)
    Put 'src/Loc/Loc.vb' (Filler 30)
    Put 'src/Loc/Loc.Strings.vb' (Filler 50)
    Put 'src/Main_Form.Designer.vb' (Filler 10)
    Put 'src/Orphan.vb' (Filler 3)
    Put 'src/bin/Ignored.vb' (Filler 3)
    Put 'tests/T.vb' (Filler 10)
    Put 'docs/RELEASE_QUEUE.md' @(
        '# queue',
        '--  001_SPECIFICATION_FIRST.md                            2026-01-01  Ready',
        '--  057_SPECIFICATION_FULL_CODE_AUDIT_PRE_RELEASE.md      2026-01-01  Proposal',
        '--  099_SPECIFICATION_LAST.md                             2026-01-01  Ready')
    Put 'docs/README.md' @(
        '# tickets',
        'The next available number is',
        '**061**. Create a new specification with that number.',
        '',
        '| Ticket | Specification | State |',
        '| --- | --- | --- |',
        '| 057 | Full code audit | umbrella |',
        '| 060 | Something else | Ready |',
        '',
        'Moved to done/: nothing.')
    Put 'docs/done/061_SPECIFICATION_ALREADY_SHIPPED.md' @('# shipped')

    $out = Join-Path $fx 'out'
    $common = @('-Root', $fx, '-OutDir', $out)
    $specArgs = @('-SpecDir', (Join-Path $fx 'docs'))
    $specDir = Join-Path $fx 'docs'
    function Get-SliceTickets { @(Get-ChildItem -LiteralPath $specDir -Filter '*_SPECIFICATION_AUDIT_SLICE_*.md' -File) + @(Get-ChildItem -LiteralPath (Join-Path $specDir 'done') -Filter '*_SPECIFICATION_AUDIT_SLICE_*.md' -File) }
    $partArgs = $common + @('-MaxFiles', '4', '-MaxLines', '100', '-FindingTickets', (Join-Path $fx 'none.md'))
    $manifestPath = Join-Path $out 'manifest.json'

    # --- status before anything exists -------------------------------------------
    $r = Run 'Audit-Status.ps1' ($common + $specArgs)
    Assert ($r.Code -eq 2) 'status: no manifest -> exit 2 (COULD NOT VERIFY)'

    # --- partition -------------------------------------------------------------------
    $r = Run 'Audit-Partition.ps1' $partArgs
    Assert ($r.Code -eq 0) "partition runs (exit $($r.Code))"
    $bytes1 = [System.IO.File]::ReadAllBytes($manifestPath)
    $m = Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json
    $membership = @{}
    foreach ($s in $m.slices) { foreach ($f in $s.files) { if (-not $membership[$f.path]) { $membership[$f.path] = @() }; $membership[$f.path] += $s.name } }
    $classA = 'src/Big/A.vb', 'src/Big/B.vb', 'src/Big/C.vb', 'src/Big/D.vb', 'src/Big/E.vb', 'src/Main_Form.Foo.vb', 'src/Foo.vb', 'src/Small.vb', 'src/Mid1.vb', 'src/Mid2.vb', 'src/Loc/Loc.vb'
    Assert (@($classA | Where-Object { @($membership[$_]).Count -ne 1 }).Count -eq 0) 'partition: every mapped class A file is in exactly one slice'
    Assert (@($m.slices | Where-Object { $_.lines -gt 100 -or $_.fileCount -gt 4 }).Count -eq 0) 'partition: no slice over 100 lines or 4 files'
    Assert (@($m.slices | Where-Object { $_.concern -eq 'X-big' }).Count -ge 3) 'partition: the oversized concern is split'
    Assert (@($m.slices | Where-Object { @($_.mergedFrom) -contains 'Y-small' }).Count -ge 1 -and -not ($m.slices | Where-Object { $_.concern -eq 'Y-small' })) 'partition: the small concern is merged into its neighbour'
    Assert ($membership['src/Main_Form.Foo.vb'] -and ($membership['src/Main_Form.Foo.vb'][0] -eq $membership['src/Foo.vb'][0])) 'partition: Main_Form.Foo.vb stays with its helper Foo.vb'
    Assert (@($m.unmapped | Where-Object { $_.path -eq 'src/Orphan.vb' }).Count -eq 1) 'partition: the unmapped file is reported'
    Assert (@($m.excluded | Where-Object { $_.path -eq 'src/Main_Form.Designer.vb' -and $_.reason }).Count -eq 1) 'partition: the Designer file is excluded with its reason'
    Assert (-not $membership['src/bin/Ignored.vb'] -and -not ($m.unmapped | Where-Object { $_.path -like '*Ignored*' })) 'partition: a bin/ folder is skipped'
    $loc = @($m.data | Where-Object { $_.path -eq 'src/Loc/Loc.Strings.vb' })
    Assert ($loc.Count -eq 1 -and $loc[0].sampledBy -and $loc[0].sampledBy -eq $membership['src/Loc/Loc.vb'][0]) 'partition: the string table is data, sampled by the slice holding its engine'
    $foo = $m.slices | Where-Object { $_.name -eq $membership['src/Main_Form.Foo.vb'][0] }
    Assert (@($foo.signals.addHandlerUnmatched).Count -eq 1 -and @($foo.signals.silentCatch).Count -eq 1) 'partition: an unmatched AddHandler and a Debug-only Catch are counted'

    $r = Run 'Audit-Partition.ps1' $partArgs
    $bytes2 = [System.IO.File]::ReadAllBytes($manifestPath)
    Assert ($r.Code -eq 0 -and [System.Linq.Enumerable]::SequenceEqual($bytes1, $bytes2)) 'partition: a repeated run writes the same manifest, byte for byte'

    $outB = Join-Path $fx 'outB'
    $r = Run 'Audit-Partition.ps1' (@('-Root', $fx, '-OutDir', $outB, '-MaxFiles', '4', '-MaxLines', '100', '-FindingTickets', (Join-Path $fx 'none.md'), '-IncludeClassB'))
    $mb = Get-Content -LiteralPath (Join-Path $outB 'manifest.json') -Raw | ConvertFrom-Json
    $aSlicesA = (@($m.slices | ForEach-Object { (@($_.files | ForEach-Object { $_.path }) -join ',') }) | Sort-Object) -join ';'
    $aSlicesB = (@($mb.slices | Where-Object { -not $_.classB } | ForEach-Object { (@($_.files | ForEach-Object { $_.path }) -join ',') }) | Sort-Object) -join ';'
    $bFiles = @($mb.slices | Where-Object { $_.classB } | ForEach-Object { $_.files } | ForEach-Object { $_.path })
    Assert ($r.Code -eq 0 -and $aSlicesA -eq $aSlicesB -and ($bFiles -contains 'tests/T.vb')) '-IncludeClassB only adds the class B files'

    # --- fan-out ---------------------------------------------------------------------
    $queue = Join-Path $fx 'docs\RELEASE_QUEUE.md'
    $readme = Join-Path $fx 'docs\README.md'
    $fanArgs = $common + $specArgs + @('-Registry', (Join-Path $fx 'none.md'), '-Date', '2026-02-02')
    $r = Run 'Audit-FanOut.ps1' $fanArgs
    $sliceFiles = @(Get-SliceTickets | Sort-Object Name)
    $nSlices = @($m.slices).Count
    Assert ($r.Code -eq 0 -and $sliceFiles.Count -eq $nSlices) "fan-out: one ticket per slice ($($sliceFiles.Count))"
    $expected = @(for ($i = 0; $i -lt $nSlices; $i++) { '{0:000}_SPECIFICATION_AUDIT_SLICE_{1}.md' -f (62 + $i), $m.riskOrder[$i].ToUpperInvariant().Replace('-', '_') })
    Assert ((@($sliceFiles | ForEach-Object Name) -join ',') -eq ($expected -join ',')) 'fan-out: tickets numbered in risk order from the next free number (061 is taken in done/)'
    $rd = [System.IO.File]::ReadAllText($readme)
    $rows = @([regex]::Matches($rd, '(?m)^\| (\d{3}) \| Audit slice 057\.') | ForEach-Object { $_.Groups[1].Value })
    Assert ($rows.Count -eq $nSlices -and $rd -match ('\*\*{0:000}\*\*' -f (62 + $nSlices)) -and $rd -match '(?s)\| 060 \|.*\| 062 \|.*Moved to done') 'fan-out: README gets one row per ticket after the last row, and the next number moves on'
    $q = [System.IO.File]::ReadAllLines($queue)
    $umb = [array]::IndexOf($q, ($q | Where-Object { $_ -match '057_SPECIFICATION' } | Select-Object -First 1))
    $block = @($q | Select-Object -Skip ($umb + 1) -First $nSlices | ForEach-Object { if ($_ -match '^--  (\d{3}_SPECIFICATION_AUDIT_SLICE_\w+\.md)') { $Matches[1] } })
    Assert (($block -join ',') -eq ($expected -join ',')) 'fan-out: the queue block sits under the umbrella, in risk order'
    Assert ($q[1] -match '001_SPECIFICATION_FIRST' -and $q[$q.Count - 1] -match '099_SPECIFICATION_LAST' -and $q.Count -eq 4 + @($m.slices).Count) 'fan-out: existing queue lines untouched'
    $firstSlice = [System.IO.File]::ReadAllText($sliceFiles[0].FullName)
    Assert ($firstSlice -match '(?m)^> Status: \*\*Ready\*\*' -and $firstSlice -match '## Last Audit' -and $firstSlice -notmatch '\{\{') 'fan-out: a slice file is complete (status, Last Audit, no placeholder left)'

    $qBytes = [System.IO.File]::ReadAllBytes($queue)
    $rdBytes = [System.IO.File]::ReadAllBytes($readme)
    $sliceBytes = @{}; foreach ($f in $sliceFiles) { $sliceBytes[$f.Name] = [System.IO.File]::ReadAllBytes($f.FullName) }
    $r = Run 'Audit-FanOut.ps1' $fanArgs
    $same = [System.Linq.Enumerable]::SequenceEqual($qBytes, [System.IO.File]::ReadAllBytes($queue)) -and [System.Linq.Enumerable]::SequenceEqual($rdBytes, [System.IO.File]::ReadAllBytes($readme))
    foreach ($f in $sliceFiles) { if (-not [System.Linq.Enumerable]::SequenceEqual($sliceBytes[$f.Name], [System.IO.File]::ReadAllBytes($f.FullName))) { $same = $false } }
    Assert ($r.Code -eq 0 -and $same -and @(Get-SliceTickets).Count -eq $sliceFiles.Count) 'fan-out: a second run creates nothing and changes no byte (tickets, queue, README)'

    # --- status ----------------------------------------------------------------------
    $statusArgs = $common + $specArgs
    $r = Run 'Audit-Status.ps1' $statusArgs
    Assert ($r.Code -eq 1 -and $r.Out -match 'open slice: ' -and $r.Out -match 'uncovered: src/Orphan\.vb') 'status: open slices and the unmapped file -> exit 1, each named'

    Remove-Item -LiteralPath (Join-Path $fx 'src\Orphan.vb')
    $done = "## Last Audit`n`n2026-02-02; all files read; no finding.`n"
    foreach ($f in $sliceFiles) {
        $t = [System.IO.File]::ReadAllText($f.FullName)
        $t = $t -replace '(?m)^> Status: \*\*Ready\*\*', '> Status: **Done**'
        $t = [regex]::Replace($t, '(?ms)^## Last Audit\s*\n.*\z', $done)
        [System.IO.File]::WriteAllText($f.FullName, $t)
    }
    # A closed slice ticket moves to done/ like any other; status still finds it.
    Move-Item -LiteralPath $sliceFiles[0].FullName -Destination (Join-Path $specDir 'done')
    $sliceFiles = @(Get-SliceTickets | Sort-Object Name)
    $r = Run 'Audit-Status.ps1' $statusArgs
    Assert ($r.Code -eq 0 -and $r.Out -match 'Audit-Status: PASS') "status: every slice done, nothing uncovered -> exit 0 (got $($r.Code))"

    # A file added after the partition: uncovered, then collected by -Tail.
    Put 'src/Mid3.vb' (Filler 12)
    $r = Run 'Audit-Status.ps1' $statusArgs
    Assert ($r.Code -eq 1 -and $r.Out -match 'uncovered: src/Mid3\.vb \(concern Z-mid') 'status: a file added after the partition -> exit 1, named with its concern'
    $qBefore = @([System.IO.File]::ReadAllLines($queue)).Count
    $r = Run 'Audit-FanOut.ps1' ($fanArgs + @('-Tail'))
    $tailFile = @(Get-SliceTickets | Where-Object { $_.Name -match '_AUDIT_SLICE_S\d+_TAIL\.md$' })
    Assert ($r.Code -eq 0 -and $tailFile.Count -eq 1 -and @([System.IO.File]::ReadAllLines($queue)).Count -eq $qBefore + 1) 'fan-out -Tail: one tail slice and one queue line'
    $t = [System.IO.File]::ReadAllText($tailFile[0].FullName) -replace '(?m)^> Status: \*\*Ready\*\*', '> Status: **Done**'
    [System.IO.File]::WriteAllText($tailFile[0].FullName, [regex]::Replace($t, '(?ms)^## Last Audit\s*\n.*\z', $done))
    $r = Run 'Audit-Status.ps1' $statusArgs
    Assert ($r.Code -eq 0) "status: the tail slice closes the gap -> exit 0 (got $($r.Code))"

    # A P1 without a disposition that accounts for it.
    $victim = $sliceFiles[0].FullName
    $orig = [System.IO.File]::ReadAllText($victim)
    $withP1 = $orig.Replace("## Last Audit", "| 057.S01-1 | P1 | Confirmed | both | src/Big/A.vb:1 | loses a file | unit test | open |`n`n## Last Audit")
    [System.IO.File]::WriteAllText($victim, $withP1)
    $r = Run 'Audit-Status.ps1' $statusArgs
    Assert ($r.Code -eq 1 -and $r.Out -match '057\.S01-1 \(P1\)') 'status: a P1 with neither ticket nor inline fix -> exit 1, named'
    [System.IO.File]::WriteAllText($victim, $orig)

    # A doubled file.
    $raw = Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json
    $raw.slices[1].files = @($raw.slices[1].files) + @($raw.slices[0].files[0])
    ($raw | ConvertTo-Json -Depth 20) | Set-Content -LiteralPath $manifestPath -Encoding utf8
    $r = Run 'Audit-Status.ps1' $statusArgs
    Assert ($r.Code -eq 1 -and $r.Out -match 'doubled: ') 'status: a file in two slices -> exit 1, named'
} finally {
    if (-not $Keep -and (Test-Path -LiteralPath $fx)) { Remove-Item -LiteralPath $fx -Recurse -Force -ErrorAction SilentlyContinue }
    elseif ($Keep) { Write-Host "  fixture kept: $fx" }
}

if ($failures.Count -gt 0) { Exit-Verdict 'AuditCampaign' 1 "$($failures.Count) of $($passed + $failures.Count) assertions failed" }
Exit-Verdict 'AuditCampaign' 0 "$passed assertions"
